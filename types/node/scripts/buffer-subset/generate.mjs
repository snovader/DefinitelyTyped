async function writeOrCheck(file, content) {
    if (check) {
        if (await readFile(file, "utf8") !== content) throw new Error("Stale declarations: " + file);
    } else {
        await mkdir(dirname(file), { recursive: true });
        await writeFile(file, content);
    }
}

async function emit(name, body) {
    const content = "// Generated by scripts/buffer-subset/generate.mjs from the Node declarations.\n" + body.trimEnd() + "\n";
    await writeOrCheck(join(root, name), content);
}

// Fail on layout changes rather than silently dropping parts of the public API.
function between(text, begin, end) {
    const start = text.indexOf(begin);
    const stop = text.indexOf(end, start + begin.length);
    if (start === -1 || stop === -1) throw new Error("Missing declaration boundary: " + begin + " ... " + end);
    return text.slice(start + begin.length, stop);
}

function unindent(text, spaces) {
    return text.replace(new RegExp("^ {" + spaces + "}", "gm"), "");
}

