import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const check = process.argv.includes("--check");
const source = name => readFile(join(root, name), "utf8");

async function writeOrCheck(file, content) {
    if (check) {
        if (await readFile(file, "utf8") !== content) throw new Error("Stale declarations: " + file);
    } else {
        await mkdir(dirname(file), { recursive: true });
        await writeFile(file, content);
    }
}

async function emit(name, body) {
    const content = "// Generated by scripts/buffer-subset/generate.mjs from the Node declarations.\n" + body.trimEnd() + "\n";
    await writeOrCheck(join(root, name), content);
}

// Fail on layout changes rather than silently dropping parts of the public API.
function between(text, begin, end) {
    const start = text.indexOf(begin);
    const stop = text.indexOf(end, start + begin.length);
    if (start === -1 || stop === -1) throw new Error("Missing declaration boundary: " + begin + " ... " + end);
    return text.slice(start + begin.length, stop);
}

function unindent(text, spaces) {
    return text.replace(new RegExp("^ {" + spaces + "}", "gm"), "");
}

for (const legacy of [false, true]) {
    const prefix = legacy ? "ts5.6/" : "";
    const arrayBody = unindent(between(await source(prefix + "globals.typedarray.d.ts"), "    namespace NodeJS {\n", "\n    }\n}"), 8);
    const arrayTypes = arrayBody.replace(/^type /gm, "export type ") + "\nexport type BufferSource = NonSharedArrayBufferView | ArrayBuffer;\n";
    // Keep Float16Array module-local when the consumer selects an older ES library.
    // The upstream 5.7 shape is also compatible with newer generic Float16Array types.
    const shim = await source((legacy ? "ts5.6" : "ts5.7") + "/compatibility/float16array.d.ts");
    await emit(prefix + "select/byte-types.d.ts", shim + "\n" + arrayTypes);
}

const util = await source("util.d.ts");
const encoding = 'export interface TextDecoderCommon' + unindent(between(util,
    '    export interface TextDecoderCommon', '    export interface TextEncoderEncodeIntoResult'), 4);
const iterator = between(await source("legacy/globals.d.ts"), '    /** An async iterable iterator returned by the Node.js API. */\n', '\n    /**');
await emit("select/stream-dependencies.d.ts", 'import type { AbortSignal } from "./abortcontroller.js";\n\n' +
    'export type HostAbortSignal = typeof globalThis extends { AbortSignal: { prototype: infer S } } ? S : AbortSignal;\n\n' +
    unindent(iterator, 4).replace("interface AsyncIterator<", "export interface NodeAsyncIterator<")
        .replaceAll("NodeJS.AsyncIterator", "NodeAsyncIterator") + "\n\n" + encoding);

for (const name of ["events", "abortcontroller"]) {
    const original = await source("web-globals/" + name + ".d.ts");
    const start = original.indexOf("type _");
    if (start === -1) throw new Error("Missing Web API fallback in " + name);
    const fallback = original.slice(start, original.indexOf("declare global {"))
        .replace(/^type _[^\n]+\n/gm, "").replace(/^interface /gm, "export interface ");
    const dependencies = name === "events" ? 'import type { HostAbortSignal as AbortSignal } from "./stream-dependencies.js";' :
        'import type { AddEventListenerOptions, Event, EventListener, EventListenerObject, EventListenerOptions, EventTarget } from "./events.js";\n\n' +
        unindent("type InternalEventTargetEventProperties<T> = " + between(await source("events.d.ts"),
            "type InternalEventTargetEventProperties<T> = ", "\n        };") + "\n        };", 8);
    await emit("select/" + name + ".d.ts", dependencies + "\n\n" + fallback);
}
